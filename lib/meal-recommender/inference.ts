/**
 * Main entry point for LightGBM meal ranking - replaces LLM call
 * 
 * This function is the drop-in replacement for the Groq API call in generateMealPlanForUser.
 * It maintains the same interface contract to ensure zero-disruption migration.
 * 
 * Flow:
 * 1. Import Supabase client for database queries
 * 2. Fetch candidate meals from meals table filtered by meal slot
 * 3. Engineer features for all candidates
 * 4. Run model inference (or fallback heuristic)
 * 5. Rank meals and select top 5
 * 6. Map Meal objects to MealSuggestion format
 * 7. Return array matching existing API contract
 * 
 * Requirements Mapping:
 * - Requirement 7: Replace LLM call while preserving function signature
 * - Requirement 6: Rank meals and return top 5 in expected format
 * - Requirement 5: Real-time feature engineering for inference
 * - Requirement 13: Graceful fallback if model fails
 * 
 * @param userId - User ID for fetching profile and meal logs
 * @param mealType - Requested meal slot (breakfast/lunch/dinner/snack) or undefined for any
 * @param profileData - User's nutrition profile with preferences
 * @param remainingMacros - User's remaining macros for today
 * @returns Promise<MealSuggestion[]> - Top 5 meal recommendations
 */
export async function rankMeals(
  userId: string,
  mealType: string | undefined,
  profileData: ProfileContext,
  remainingMacros: RemainingMacros
): Promise<MealSuggestion[]> {
  try {
    console.log(`[rankMeals] Starting meal ranking for user ${userId}, meal type: ${mealType || 'any'}`);
    console.log(`[rankMeals] Full profile data:`, profileData);
    console.log(`[rankMeals] Profile cuisine_preference:`, profileData.cuisine_preference);
    console.log(`[rankMeals] Profile has cuisine_preference key:`, 'cuisine_preference' in profileData);
    
    // Import Supabase client
    const { createServerClient } = await import('@/lib/supabase/server');
    const supabase = createServerClient();
    
    // Fetch candidate meals from meals table
    // Filter by meal_slot if mealType is specified
    // Filter by cuisine_type if user has a cuisine preference
    let query = supabase
      .from('meals')
      .select('*');
    
    if (mealType) {
      query = query.eq('meal_slot', mealType);
    }
    
    // HARD FILTER: Only show meals matching user's cuisine preference if set
    if (profileData.cuisine_preference) {
      query = query.eq('cuisine_type', profileData.cuisine_preference);
      console.log(`[rankMeals] Filtering meals by cuisine: ${profileData.cuisine_preference}`);
    }
    
    const { data: candidateMeals, error: mealsError } = await query;
    
    if (mealsError) {
      console.error('[rankMeals] Error fetching candidate meals:', mealsError);
      return [];
    }
    
    if (!candidateMeals || candidateMeals.length === 0) {
      console.warn('[rankMeals] No candidate meals found');
      return [];
    }
    
    console.log(`[rankMeals] Found ${candidateMeals.length} candidate meals`);
    
    // Map database meals to Meal type for ranking
    const meals: Meal[] = candidateMeals.map((dbMeal: any) => ({
      id: dbMeal.id,
      name: dbMeal.name,
      description: dbMeal.description,
      cuisine_type: dbMeal.cuisine_type || '',
      meal_slot: dbMeal.meal_slot || '',
      calories: dbMeal.calories || 0,
      protein_g: dbMeal.protein_g || 0,
      carbs_g: dbMeal.carbs_g || 0,
      fat_g: dbMeal.fat_g || 0,
      ingredients: dbMeal.ingredients || []
    }));
    
    // Prepare user profile for feature engineering
    const userProfile: UserProfile = {
      cuisine_preference: profileData.cuisine_preference || null
    };
    
    // Rank meals using the trained model or fallback heuristic
    const requestedSlot = mealType || 'any';
    const rankedMeals = await rankAndSelectTop5(
      userProfile,
      meals,
      remainingMacros,
      userId,
      requestedSlot,
      supabase
    );
    
    // Map ranked Meal objects to MealSuggestion format
    const mealSuggestions: MealSuggestion[] = rankedMeals.map((meal: Meal) => ({
      meal_type: meal.meal_slot,
      meal_name: meal.name,
      description: meal.description || '',
      items: meal.ingredients || [],
      calories: Math.round(meal.calories),
      protein_g: Math.round(meal.protein_g),
      carbs_g: Math.round(meal.carbs_g),
      fat_g: Math.round(meal.fat_g)
    }));
    
    console.log(`[rankMeals] Returning ${mealSuggestions.length} meal recommendations`);
    
    // Log recommendation event (fire-and-forget, non-blocking)
    // This captures recommendation context for future model retraining
    if (rankedMeals.length > 0) {
      const { logRecommendation } = await import('@/lib/meal-recommender/logger');
      const mealIds = rankedMeals.map(m => m.id);
      logRecommendation(userId, mealIds, requestedSlot, profileData, remainingMacros);
    }
    
    return mealSuggestions;
    
  } catch (error) {
    console.error('[rankMeals] Unexpected error:', error);
    // Return empty array to maintain service availability
    // Caller can handle empty results gracefully
    return [];
  }
}
