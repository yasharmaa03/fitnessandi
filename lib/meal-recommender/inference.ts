/**
 * Compute fallback heuristic scores when model is unavailable.
 * 
 * Heuristic: score = -sqrt(sum(macro_delta^2))
 * 
 * Rationale:
 * - Euclidean distance in macro space measures "fit quality"
 * - Smaller distance = better fit (meal closely matches remaining needs)
 * - Negative sign ensures higher scores = better (for consistent sorting)
 * - sqrt prevents large macro deltas from dominating
 * 
 * Example:
 * - Meal A: deltas = [20, 2, 2, 1] → score = -√(400+4+4+1) = -√409 = -20.2
 * - Meal B: deltas = [300, 20, 20, 10] → score = -√(90000+400+400+100) = -√90900 = -301.5
 * - Meal A scores higher (better fit)
 * 
 * This provides a reasonable ranking without ML model, ensuring service continuity.
 * 
 * @param meals - Array of meal objects
 * @param remaining - User's remaining macros
 * @returns Array of heuristic scores (one per meal)
 */
export function fallbackHeuristicRanking(meals: Meal[], remaining: RemainingMacros): number[] {
  const scores: number[] = [];
  
  for (const meal of meals) {
    // Compute macro deltas (same as features 1-4)
    const deltaCalories = Math.abs(meal.calories - remaining.calories);
    const deltaProtein = Math.abs(meal.protein_g - remaining.protein_g);
    const deltaCarbs = Math.abs(meal.carbs_g - remaining.carbs_g);
    const deltaFat = Math.abs(meal.fat_g - remaining.fat_g);
    
    // Compute Euclidean distance
    const sumSquares = 
      deltaCalories * deltaCalories +
      deltaProtein * deltaProtein +
      deltaCarbs * deltaCarbs +
      deltaFat * deltaFat;
    
    // Negative sqrt for "higher is better" scoring
    const score = -Math.sqrt(sumSquares);
    
    scores.push(score);
  }
  
  return scores;
}

