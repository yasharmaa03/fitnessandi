/**
 * Compute macro delta features: absolute difference between meal and remaining macros.
 * 
 * MIRRORS: train.py → compute_macro_delta()
 * 
 * This is the PRIMARY feature for meal ranking. It captures how well a meal "fits"
 * the user's remaining nutritional needs for the day.
 * 
 * Rationale:
 * - Small deltas = meal closely matches remaining needs (GOOD fit)
 * - Large deltas = meal overshoots or undershoots needs (POOR fit)
 * - Absolute values ensure we penalize both overshooting and undershooting
 * 
 * Example:
 * - User has 500 calories remaining
 * - Meal A: 480 calories → delta = 20 (excellent fit)
 * - Meal B: 800 calories → delta = 300 (poor fit, too much)
 * - Meal C: 200 calories → delta = 300 (poor fit, too little)
 * 
 * @param meal - Meal object with nutritional information
 * @param remaining - Remaining macros for the user today
 * @returns Array of 4 floats: [|calories_delta|, |protein_delta|, |carbs_delta|, |fat_delta|]
 */
export function computeMacroDelta(meal: Meal, remaining: RemainingMacros): number[] {
  // Compute absolute difference for each macro nutrient
  // This penalizes both eating too much and too little
  const caloriesDelta = Math.abs(meal.calories - remaining.calories);
  const proteinDelta = Math.abs(meal.protein_g - remaining.protein_g);
  const carbsDelta = Math.abs(meal.carbs_g - remaining.carbs_g);
  const fatDelta = Math.abs(meal.fat_g - remaining.fat_g);
  
  return [
    caloriesDelta,
    proteinDelta,
    carbsDelta,
    fatDelta
  ];
}

/**
 * Compute cuisine match feature: 1 if meal cuisine matches user preference, else 0.
 * 
 * MIRRORS: train.py → compute_cuisine_match()
 * 
 * Rationale:
 * - Users are more likely to enjoy and accept meals from their preferred cuisine
 * - This is a simple binary preference signal
 * - If user has no preference (null/undefined), all meals get 0 (no boost)
 * 
 * Example:
 * - User prefers "italian"
 * - Meal A: cuisine="italian" → match = 1 (boosted)
 * - Meal B: cuisine="mexican" → match = 0 (not boosted)
 * - Meal C: cuisine="italian" → match = 1 (boosted)
 * 
 * @param meal - Meal object with cuisine_type
 * @param userPreference - User's preferred cuisine type (or null/undefined for no preference)
 * @returns 1 if match, 0 if no match or no preference
 */
export function computeCuisineMatch(meal: Meal, userPreference: string | null | undefined): number {
  // If user has no preference, return 0 (no boost)
  if (!userPreference) {
    return 0;
  }
  
  // Check if meal's cuisine matches user's preference (case-insensitive)
  const mealCuisine = meal.cuisine_type?.toLowerCase() || '';
  const userPrefLower = userPreference.toLowerCase();
  
  return mealCuisine === userPrefLower ? 1 : 0;
}

/**
 * Compute meal slot match feature: 1 if meal fits requested slot, else 0.
 * 
 * MIRRORS: train.py → compute_meal_slot_match()
 * 
 * Rationale:
 * - Meals are categorized as breakfast, lunch, dinner, or snack
 * - Users request meals for specific slots (e.g., "I need breakfast")
 * - Matching the slot ensures appropriate meals (no dinner for breakfast)
 * - This is a HARD constraint feature - mismatches should be heavily penalized
 * 
 * Example:
 * - User requests "breakfast"
 * - Meal A: meal_slot="breakfast" → match = 1 (appropriate)
 * - Meal B: meal_slot="dinner" → match = 0 (inappropriate, too heavy)
 * - Meal C: meal_slot="snack" → match = 0 (inappropriate, too light)
 * 
 * @param meal - Meal object with meal_slot
 * @param requestedSlot - The meal slot being requested by the user
 * @returns 1 if match, 0 if no match
 */
export function computeMealSlotMatch(meal: Meal, requestedSlot: string): number {
  // Check if meal's slot matches the requested slot (case-insensitive)
  const mealSlot = meal.meal_slot?.toLowerCase() || '';
  const requestedSlotLower = requestedSlot.toLowerCase();
  
  return mealSlot === requestedSlotLower ? 1 : 0;
}

/**
 * Compute days since user last ate this meal (recency feature).
 * 
 * MIRRORS: train.py → compute_days_since_last_eaten()
 * 
 * Rationale:
 * - Users want VARIETY in their meal recommendations
 * - Recently eaten meals should be deprioritized (avoid repetition)
 * - Never-eaten meals should be boosted (encourage exploration)
 * - Use 999 as default for never-eaten to strongly boost new meals
 * 
 * Example:
 * - Today is Day 100
 * - Meal A: last eaten Day 98 → recency = 2 days (very recent, penalize)
 * - Meal B: last eaten Day 85 → recency = 15 days (moderate, neutral)
 * - Meal C: never eaten → recency = 999 days (boost exploration)
 * 
 * Implementation:
 * - Queries meal_logs table for this meal_name and user_id
 * - Calculates days between today and most recent log
 * - Returns 999 if meal never logged by this user
 * 
 * @param mealId - Meal identifier (matches meal name in meal_logs)
 * @param userId - User identifier
 * @param supabase - Supabase client for database queries
 * @returns Promise<number> - Days since last eaten (999 if never eaten)
 */
export async function computeDaysSinceLastEaten(
  mealId: string,
  userId: string,
  supabase: any
): Promise<number> {
  try {
    // Query meal_logs for the most recent log of this meal by this user
    // We match on meal_name since meal_logs doesn't have a meal_id foreign key
    const { data, error } = await supabase
      .from('meal_logs')
      .select('logged_at')
      .eq('user_id', userId)
      .eq('meal_name', mealId)
      .order('logged_at', { ascending: false })
      .limit(1);
    
    if (error) {
      console.error('[Feature Engineering] Error querying meal_logs:', error);
      return 999; // Default to never eaten on error
    }
    
    if (!data || data.length === 0) {
      // Meal never logged by this user
      return 999;
    }
    
    // Calculate days since last eaten
    const lastEatenDate = new Date(data[0].logged_at);
    const today = new Date();
    const diffMs = today.getTime() - lastEatenDate.getTime();
    const daysSince = Math.floor(diffMs / (1000 * 60 * 60 * 24));
    
    return daysSince;
  } catch (error) {
    console.error('[Feature Engineering] Exception in computeDaysSinceLastEaten:', error);
    return 999; // Default to never eaten on exception
  }
}

/**
 * Compute complete 7-feature vector for a (user, meal) pair.
 * 
 * MIRRORS: train.py → engineer_features()
 * 
 * This is the MAIN feature engineering function that combines all individual
 * features into the final input vector for the LightGBM model.
 * 
 * Feature Vector (7 elements in this exact order):
 * 1. macro_delta_calories: |meal.calories - remaining.calories|
 * 2. macro_delta_protein: |meal.protein_g - remaining.protein_g|
 * 3. macro_delta_carbs: |meal.carbs_g - remaining.carbs_g|
 * 4. macro_delta_fat: |meal.fat_g - remaining.fat_g|
 * 5. cuisine_match: 1 if meal.cuisine matches user.cuisine_preference else 0
 * 6. meal_slot_match: 1 if meal.meal_slot matches requested_slot else 0
 * 7. days_since_last_eaten: days since user ate this meal (999 if never)
 * 
 * Feature Rationale:
 * - Features 1-4 (macro deltas): Capture nutritional fit quality
 * - Feature 5 (cuisine): Captures user taste preference
 * - Feature 6 (meal slot): Ensures meal appropriateness for time of day
 * - Feature 7 (recency): Encourages variety and exploration
 * 
 * Example:
 * User wants breakfast, prefers Italian, has 400 cal/30g protein/40g carbs/15g fat remaining
 * 
 * Meal A: Italian breakfast, 380 cal/28g protein/38g carbs/14g fat, eaten 5 days ago
 * → [20, 2, 2, 1, 1, 1, 5] (excellent fit - all features align)
 * 
 * Meal B: Mexican dinner, 700 cal/50g protein/60g carbs/25g fat, never eaten
 * → [300, 20, 20, 10, 0, 0, 999] (poor fit - wrong slot, too much food)
 * 
 * @param profile - User profile with cuisine_preference
 * @param meal - Meal object with nutritional info and metadata
 * @param remaining - Remaining macros for the user
 * @param userId - User ID for recency calculation
 * @param requestedSlot - Meal slot being requested (breakfast/lunch/dinner/snack)
 * @param supabase - Supabase client for database queries
 * @returns Promise<number[]> - 7-element feature vector
 */
export async function computeFeatures(
  profile: UserProfile,
  meal: Meal,
  remaining: RemainingMacros,
  userId: string,
  requestedSlot: string,
  supabase: any
): Promise<number[]> {
  // Feature 1-4: Macro delta features (nutritional fit)
  // TRAINING MAPPING: train.py lines 350-365
  const macroDeltas = computeMacroDelta(meal, remaining);
  
  // Feature 5: Cuisine match (taste preference)
  // TRAINING MAPPING: train.py lines 368-395
  const cuisineMatch = computeCuisineMatch(meal, profile.cuisine_preference);
  
  // Feature 6: Meal slot match (appropriateness for time of day)
  // TRAINING MAPPING: train.py lines 398-425
  const mealSlotMatch = computeMealSlotMatch(meal, requestedSlot);
  
  // Feature 7: Recency (variety and exploration)
  // TRAINING MAPPING: train.py lines 428-465
  const daysSince = await computeDaysSinceLastEaten(meal.name, userId, supabase);
  
  // Combine all features into final 7-element vector
  // ORDER MATTERS - this must match the training schema
  const featureVector = [
    macroDeltas[0],  // macro_delta_calories
    macroDeltas[1],  // macro_delta_protein
    macroDeltas[2],  // macro_delta_carbs
    macroDeltas[3],  // macro_delta_fat
    cuisineMatch,    // cuisine_match
    mealSlotMatch,   // meal_slot_match
    daysSince        // days_since_last_eaten
  ];
  
  return featureVector;
}

